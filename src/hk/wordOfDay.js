// Days since 2026-01-01 in Chicago -> the index; the same for every viewer on a Chicago day.
export function chicagoDay(now = new Date()) {
  return new Date(now).toLocaleDateString('en-CA', { timeZone: 'America/Chicago' });
}
export function wordFor(now = new Date()) {
  const day = chicagoDay(now);
  const n = Math.round((Date.parse(`${day}T12:00:00Z`) - Date.parse('2026-01-01T12:00:00Z')) / 864e5);
  const [word, definition, example] = WORDS[((n % WORDS.length) + WORDS.length) % WORDS.length];
  return { day, word, definition, example };
}

// The other founder to nudge: a signed-up member who isn't me and hasn't loaded the shell in 3+ days (an unknown
// last_seen_at never nudges).
export const NUDGE_DAYS = 3;
export function checkInWith(me, members = [], now = Date.now()) {
  const other = members.find(m => m.signed_up && m.user_id && m.user_id !== me?.user_id && m.last_seen_at && now - Date.parse(m.last_seen_at) >= NUDGE_DAYS * 864e5);
  return other ? other.first_name : null;
}
